let lang = detectLang();
if (!I18N[lang]) lang = "en";

function detectLang() {
  try {
    if (localStorage.getItem("catbox-lang-on") === "1") {
      const saved = localStorage.getItem("catbox-lang");
      if (saved && I18N[saved]) return saved;
    }
  } catch (_) {}
  let nav = "";
  try {
    nav = `${navigator.language || ""} ${(navigator.languages || []).join(" ")}`.toLowerCase();
  } catch (_) {}
  if (/zh/.test(nav)) return "zh";
  if (/\bja\b/.test(nav)) return "ja";
  if (/\bko\b/.test(nav)) return "ko";
  if (/\bvi\b/.test(nav)) return "vi";
  if (/\bth\b/.test(nav)) return "th";
  if (/\bru\b/.test(nav)) return "ru";
  return "en";
}

function t(key, vars = {}) {
  const pack = I18N[lang] || I18N.en;
  let s = pack[key] ?? I18N.en[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    s = s.replaceAll(`{${k}}`, String(v));
  });
  return s;
}

function tierText(id) {
  return (I18N[lang] || I18N.en).tiers[id];
}

const HTML_LANG = { en: "en", zh: "zh-CN", ja: "ja", ko: "ko", vi: "vi", th: "th", ru: "ru" };

function setLang(id) {
  if (!I18N[id]) return;
  lang = id;
  localStorage.setItem("catbox-lang", lang);
  localStorage.setItem("catbox-lang-on", "1");
  applyI18n();
}

function mountLangs() {
  const nav = document.getElementById("langs");
  const now = document.getElementById("langNow");
  if (!nav) return;
  nav.innerHTML = LANGS.map(
    (l) =>
      `<button type="button" class="lang-btn${l.id === lang ? " on" : ""}" data-lang="${l.id}">${l.label}</button>`,
  ).join("");
  const syncNow = () => {
    const cur = LANGS.find((l) => l.id === lang) || LANGS[0];
    if (now) now.textContent = cur.label;
  };
  syncNow();
  if (now) {
    now.onclick = (e) => {
      e.stopPropagation();
      nav.classList.toggle("hidden");
    };
  }
  nav.onclick = (e) => {
    e.stopPropagation();
    const btn = e.target.closest("[data-lang]");
    if (!btn) return;
    setLang(btn.dataset.lang);
    nav.classList.add("hidden");
    syncNow();
  };
  document.addEventListener("click", () => nav.classList.add("hidden"));
}

function applyI18n() {
  document.documentElement.lang = HTML_LANG[lang] || lang;
  document.body.dataset.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.innerHTML = t(key).replaceAll("\n", "<br>");
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll(".lang-btn").forEach((b) => {
    b.classList.toggle("on", b.dataset.lang === lang);
  });
  const now = document.getElementById("langNow");
  if (now) {
    const cur = LANGS.find((l) => l.id === lang) || LANGS[0];
    now.textContent = cur.label;
  }
  if (typeof renderTickets === "function") renderTickets();
  if (typeof selected !== "undefined" && selected && typeof openPay === "function") {
    const payEl = document.getElementById("pay");
    if (payEl && !payEl.classList.contains("hidden")) openPay(selected);
  }
  if (typeof refreshHud === "function") refreshHud();
  if (typeof refreshOver === "function") refreshOver();
  if (typeof paintCrew === "function") paintCrew();
  if (typeof renderBoards === "function") renderBoards();
  if (typeof refreshWalletUi === "function") refreshWalletUi();
  if (typeof paintSwapGo === "function") paintSwapGo();
  if (typeof refreshSwap === "function") refreshSwap();
  if (typeof window.syncBgmUi === "function") window.syncBgmUi();
  if (typeof refreshTutorialCopy === "function") refreshTutorialCopy();
}
